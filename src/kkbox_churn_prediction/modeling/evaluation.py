from __future__ import annotations

import numpy as np
import pandas as pd

from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    precision_recall_curve,
    precision_score,
    recall_score,
    roc_auc_score,
)


def calculate_probability_metrics(
    y_true,
    probabilities,
) -> dict[str, float]:
    """
    Calculate threshold-independent metrics.

    Metrics:
    - PR-AUC
    - ROC-AUC
    - Brier Score
    """

    return {
        "pr_auc": float(
            average_precision_score(
                y_true,
                probabilities,
            )
        ),

        "roc_auc": float(
            roc_auc_score(
                y_true,
                probabilities,
            )
        ),

        "brier_score": float(
            brier_score_loss(
                y_true,
                probabilities,
            )
        ),
    }


def calculate_threshold_metrics(
    y_true,
    probabilities,
    threshold: float,
) -> dict[str, float | int]:
    """
    Calculate classification metrics
    using a fixed probability threshold.
    """

    probabilities = np.asarray(
        probabilities
    )

    predictions = (
        probabilities >= threshold
    ).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        predictions,
        labels=[0, 1],
    ).ravel()

    return {
        "threshold": float(
            threshold
        ),

        "precision": float(
            precision_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "recall": float(
            recall_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "f1": float(
            f1_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),

        "predicted_positive_rate": float(
            predictions.mean()
        ),
    }


def build_threshold_table(
    y_true,
    probabilities,
) -> pd.DataFrame:
    """
    Build Precision / Recall / F1 table
    for all thresholds generated by
    precision_recall_curve().
    """

    (
        precision,
        recall,
        thresholds,
    ) = precision_recall_curve(
        y_true,
        probabilities,
    )

    # precision_recall_curve returns
    # one extra precision/recall value.
    precision = precision[:-1]
    recall = recall[:-1]

    denominator = (
        precision + recall
    )

    f1 = np.divide(
        2 * precision * recall,
        denominator,

        out=np.zeros_like(
            denominator,
            dtype=float,
        ),

        where=(
            denominator != 0
        ),
    )

    table = pd.DataFrame(
        {
            "threshold": thresholds,
            "precision": precision,
            "recall": recall,
            "f1": f1,
        }
    )

    return (
        table
        .sort_values(
            "threshold"
        )
        .reset_index(
            drop=True
        )
    )


def find_best_f1_threshold(
    threshold_table: pd.DataFrame,
) -> dict[str, float]:
    """
    Find threshold with maximum F1.
    """

    if threshold_table.empty:
        raise ValueError(
            "Threshold table is empty."
        )

    row = threshold_table.loc[
        threshold_table[
            "f1"
        ].idxmax()
    ]

    return {
        "threshold": float(
            row["threshold"]
        ),

        "precision": float(
            row["precision"]
        ),

        "recall": float(
            row["recall"]
        ),

        "f1": float(
            row["f1"]
        ),
    }


def find_threshold_for_min_recall(
    threshold_table: pd.DataFrame,
    min_recall: float,
) -> dict[str, float]:
    """
    Find highest-precision threshold
    while keeping recall >= min_recall.
    """

    if not 0 <= min_recall <= 1:
        raise ValueError(
            "min_recall must be "
            "between 0 and 1."
        )

    candidates = threshold_table[
        threshold_table[
            "recall"
        ]
        >= min_recall
    ]

    if candidates.empty:
        raise ValueError(
            "No threshold satisfies "
            f"recall >= {min_recall}."
        )

    row = candidates.loc[
        candidates[
            "precision"
        ].idxmax()
    ]

    return {
        "threshold": float(
            row["threshold"]
        ),

        "precision": float(
            row["precision"]
        ),

        "recall": float(
            row["recall"]
        ),

        "f1": float(
            row["f1"]
        ),
    }


def add_predictions_and_error_types(
    predictions_df: pd.DataFrame,
    threshold: float,
) -> pd.DataFrame:
    """
    Add:
    - prediction
    - error_type

    Required columns:
    - is_churn
    - churn_probability
    """

    result = predictions_df.copy()

    result["prediction"] = (
        result[
            "churn_probability"
        ]
        >= threshold
    ).astype(int)

    y_true = result[
        "is_churn"
    ].to_numpy()

    y_pred = result[
        "prediction"
    ].to_numpy()

    result["error_type"] = np.select(
        [
            (
                (y_true == 1)
                & (y_pred == 0)
            ),
            (
                (y_true == 0)
                & (y_pred == 1)
            ),
            (
                (y_true == 1)
                & (y_pred == 1)
            ),
        ],

        [
            "false_negative",
            "false_positive",
            "true_positive",
        ],

        default="true_negative",
    )

    return result